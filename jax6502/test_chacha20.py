class TestCrossValidateJS:
    """Byte-for-byte match against coin/chacha20.js outputs."""

    def test_zero_key_nonce_block0(self):
        key = jnp.zeros(8, dtype=jnp.uint32)
        nonce = jnp.zeros(3, dtype=jnp.uint32)
        block = chacha20_block(key, jnp.uint32(0), nonce)
        assert list(np.asarray(block)) == JS_ZERO_BLOCK0

    def test_seed_to_key(self):
        key = seed_to_key("test")
        assert list(np.asarray(key).view(np.uint8)) == JS_SEED_KEY_TEST

    def test_derive_nonce(self):
        nonce = derive_nonce(8)
        assert list(np.asarray(nonce).view(np.uint8)) == JS_NONCE_SIZE8

    def test_board_init_first64(self):
        init = generate_board_init("test", 8)
        assert list(np.asarray(init[:64])) == JS_BOARD_INIT_FIRST64

    def test_board_init_last64(self):
        init = generate_board_init("test", 8)
        assert list(np.asarray(init[-64:])) == JS_BOARD_INIT_LAST64

    def test_board_init_length(self):
        init = generate_board_init("test", 8)
        assert len(init) == 8 * 8 * 1024


# ── Stream consistency ────────────────────────────────────────────────

class TestStreamConsistency:
    """First 64 bytes of a 128-byte stream must equal a standalone block."""

    def test_first_block_matches(self):
        key = jnp.zeros(8, dtype=jnp.uint32).at[0].set(jnp.uint32(42))
        nonce = jnp.zeros(3, dtype=jnp.uint32)
        stream = chacha20_stream(key, nonce, 2)
        single = chacha20_block(key, jnp.uint32(0), nonce)
        np.testing.assert_array_equal(
            np.asarray(stream[:64]), np.asarray(single)
        )


# ── Primitives ────────────────────────────────────────────────────────

class TestPrimitives:
    def test_rotl32(self):
        assert int(rotl32(jnp.uint32(1), jnp.uint32(1))) == 2
        assert int(rotl32(jnp.uint32(0x80000000), jnp.uint32(1))) == 1
        assert int(rotl32(jnp.uint32(0xDEADBEEF), jnp.uint32(16))) == 0xBEEFDEAD

    def test_quarter_round_rfc(self):
        """RFC 7539 Section 2.1.1 quarter-round test vector."""
        # The RFC specifies a 4-value test: a=0x11111111, b=0x01020304,
        # c=0x9b8d6f43, d=0x01234567 → QUARTERROUND(0,1,2,3)
        state = jnp.zeros(16, dtype=jnp.uint32)
        state = state.at[0].set(jnp.uint32(0x11111111))
        state = state.at[1].set(jnp.uint32(0x01020304))
        state = state.at[2].set(jnp.uint32(0x9B8D6F43))
        state = state.at[3].set(jnp.uint32(0x01234567))
        result = quarter_round(state, 0, 1, 2, 3)
        assert int(result[0]) == 0xEA2A92F4
        assert int(result[1]) == 0xCB1CF8CE
        assert int(result[2]) == 0x4581472E
        assert int(result[3]) == 0x5881C4BB


# ── Determinism ───────────────────────────────────────────────────────

class TestDeterminism:
    def test_same_inputs_same_output(self):
        key = jnp.zeros(8, dtype=jnp.uint32)
        nonce = jnp.zeros(3, dtype=jnp.uint32)
        a = chacha20_stream(key, nonce, 1)
        b = chacha20_stream(key, nonce, 1)
        np.testing.assert_array_equal(np.asarray(a), np.asarray(b))

    def test_different_keys_differ(self):
        nonce = jnp.zeros(3, dtype=jnp.uint32)
        k1 = jnp.zeros(8, dtype=jnp.uint32).at[0].set(jnp.uint32(1))
        k2 = jnp.zeros(8, dtype=jnp.uint32).at[0].set(jnp.uint32(2))
        a = chacha20_stream(k1, nonce, 1)
        b = chacha20_stream(k2, nonce, 1)
        assert not np.array_equal(np.asarray(a), np.asarray(b))
