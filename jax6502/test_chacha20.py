# ── RFC 7539 §2.3.2 test vector ──────────────────────────────────────

# Key  = 00:01:02:…:1f
# Nonce = 00:00:00:09:00:00:00:4a:00:00:00:00  (LE uint32 words)
# Counter = 1

RFC_KEY_BYTES = bytes(range(32))
RFC_NONCE_BYTES = bytes([0, 0, 0, 9, 0, 0, 0, 0x4A, 0, 0, 0, 0])

# Expected output for counter=1 (from the RFC)
RFC_EXPECTED_BLOCK1 = bytes([
    0x10, 0xf1, 0xe7, 0xe4, 0xd1, 0x3b, 0x59, 0x15,
    0x50, 0x0f, 0xdd, 0x1f, 0xa3, 0x20, 0x71, 0xc4,
    0xc7, 0xd1, 0xf4, 0xc7, 0x33, 0xc0, 0x68, 0x03,
    0x04, 0x22, 0xaa, 0x9a, 0xc3, 0xd4, 0x6c, 0x4e,
    0xd2, 0x82, 0x64, 0x46, 0x07, 0x9f, 0xaa, 0x09,
    0x14, 0xc2, 0xd7, 0x05, 0xd9, 0x8b, 0x02, 0xa2,
    0xb5, 0x12, 0x9c, 0xd1, 0xde, 0x16, 0x4e, 0xb9,
    0xcb, 0xd0, 0x83, 0xe8, 0xa2, 0x50, 0x3c, 0x4e,
])


class TestRFC7539:
    """RFC 7539 Section 2.3.2 — the gold-standard test vector."""

    def test_block_counter1(self):
        key = jnp.frombuffer(RFC_KEY_BYTES, dtype=jnp.uint32)
        nonce = jnp.frombuffer(RFC_NONCE_BYTES, dtype=jnp.uint32)
        block = chacha20_block(key, jnp.uint32(1), nonce)
        assert bytes(np.asarray(block)) == RFC_EXPECTED_BLOCK1

    def test_stream_contains_block1(self):
        """chacha20_stream with 2 blocks should contain the RFC block at offset 64."""
        key = jnp.frombuffer(RFC_KEY_BYTES, dtype=jnp.uint32)
        nonce = jnp.frombuffer(RFC_NONCE_BYTES, dtype=jnp.uint32)
        stream = chacha20_stream(key, nonce, 2)
        assert bytes(np.asarray(stream[64:128])) == RFC_EXPECTED_BLOCK1


